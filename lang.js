function setLanguage(lang) {
    localStorage.setItem('selectedLang', lang);
    document.documentElement.lang = lang;
    
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            el.innerHTML = translations[lang][key];
        }
    });

    // Update dynamic portfolio items
    if (typeof projectsData !== 'undefined') {
        document.querySelectorAll('[data-project-id]').forEach(el => {
            const id = el.getAttribute('data-project-id');
            const type = el.getAttribute('data-type');
            if (projectsData[id]) {
                if (type === 'title') el.textContent = projectsData[id].title[lang] || projectsData[id].title.pt;
                if (type === 'category') el.textContent = projectsData[id].category[lang] || projectsData[id].category.pt;
                if (type === 'desc') el.textContent = projectsData[id].description[lang] || projectsData[id].description.pt;
                if (type === 'tag') {
                    const cat = projectsData[id].category[lang] || projectsData[id].category.pt;
                    if (projectsData[id].type === 'video') {
                        el.textContent = lang === 'pt' ? 'Vídeo' : 'Video';
                    } else if (cat.includes('Artwork') || cat.includes('Arte')) {
                        el.textContent = 'Artwork';
                    } else {
                        el.textContent = lang === 'es' ? 'Diseño y Social' : 'Design & Social';
                    }
                }
            }
        });
    }

    // Update active state in switcher
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.remove('active');
        if (btn.getAttribute('data-lang') === lang) {
            btn.classList.add('active');
        }
    });
    
    // Update main switcher button icon
    const currentLangIcon = document.getElementById('current-lang-icon');
    if (currentLangIcon) {
        if (lang === 'pt') currentLangIcon.textContent = '🇵🇹';
        if (lang === 'en') currentLangIcon.textContent = '🇬🇧';
        if (lang === 'es') currentLangIcon.textContent = '🇪🇸';
    }
}

// Load saved language on startup
document.addEventListener('DOMContentLoaded', () => {
    const savedLang = localStorage.getItem('selectedLang') || 'pt';
    setLanguage(savedLang);

    // Setup listeners for language dropdown
    const langSwitcher = document.querySelector('.lang-switcher');
    if (langSwitcher) {
        langSwitcher.addEventListener('click', (e) => {
            langSwitcher.classList.toggle('open');
        });

        document.querySelectorAll('.lang-btn').forEach(btn => {
            btn.addEventListener('click', (e) => {
                e.stopPropagation();
                const lang = btn.getAttribute('data-lang');
                setLanguage(lang);
                langSwitcher.classList.remove('open');
            });
        });

        // Close dropdown when clicking outside
        document.addEventListener('click', (e) => {
            if (!langSwitcher.contains(e.target)) {
                langSwitcher.classList.remove('open');
            }
        });
    }
});
